// UDFWorkerTopology describes the logical placement contract of a Python UDF
// worker. The current Operator implementation supports paired workers in the
// CN Pod only. The other values remain part of the typed API so that an
// unsupported request is rejected deterministically rather than silently
// rendered as a different topology.
type UDFWorkerTopology string

const (
	UDFWorkerTopologyDisabled UDFWorkerTopology = "disabled"
	UDFWorkerTopologyPaired   UDFWorkerTopology = "paired"
	UDFWorkerTopologyPool     UDFWorkerTopology = "pool"
)

// UDFWorkerLauncher identifies the process boundary used by the worker.
type UDFWorkerLauncher string

const (
	UDFWorkerLauncherPythonImage UDFWorkerLauncher = "python-image"
	UDFWorkerLauncherMOService   UDFWorkerLauncher = "mo-service"
)

const (
	// ContainerUDFWorker is the current worker container name. Keep the
	// historical python-udf value out of the new rendered Pod so the old demo
	// cannot be mistaken for the current worker contract.
	ContainerUDFWorker            = "udf-worker"
	ContainerUDFWorkerDefaultPort = 50051

	// UDFWorkerEnabledLabel is deliberately controller-owned. CNPool/CNClaim
	// use it to prevent a Python-enabled Pod from crossing claim owners without
	// a new Pod UID and a new CN/Gateway/worker process.
	UDFWorkerEnabledLabel = "matrixorigin.io/udf-worker-enabled"
	UDFWorkerEnabledValue = "true"
	// UDFWorkerStatusAnno is written by the CN store controller after querying
	// the CN-local Python runtime. It is intentionally bounded and tied to the
	// current Pod UID and policy generation.
	UDFWorkerStatusAnno = "matrixorigin.io/udf-worker-status"
	// UDFWorkerGenerationAnno is copied into each CN Pod template. It binds a
	// capability observation to the generation actually rendered into that Pod;
	// the CN store must not stamp the desired generation onto an old Pod.
	UDFWorkerGenerationAnno = "matrixorigin.io/udf-worker-generation"

	// The direct Python image is built with the unprivileged `mo` account. The
	// Operator repeats its numeric identity in the Pod security context because
	// Kubernetes cannot prove runAsNonRoot from a non-numeric OCI USER alone.
	// Keeping this in the API contract makes the image and rendered Pod agree.
	UDFWorkerRunAsUser  int64 = 1000
	UDFWorkerRunAsGroup int64 = 1000
)

// These ports are occupied by the CN Pod generated by the current CNSet
// renderer. The six-port range starts at the CN port-base and is allocated by
// MatrixOne's internal service address manager; 6001 is the SQL endpoint and
// 7001 is the metrics endpoint. A same-Pod Worker cannot bind any of them.
// Keep this contract in the API package so admission and restore-time
// validation do not drift between the webhook and controllers.
const (
	CNUDFWorkerReservedSQLPort     int32 = 6001
	CNUDFWorkerReservedPortBase    int32 = 6002
	CNUDFWorkerReservedPortSlots   int32 = 5
	CNUDFWorkerReservedMetricsPort int32 = 7001
)

func IsCNPodPortReservedForUDFWorker(port int32) bool {
	return port == CNUDFWorkerReservedSQLPort ||
		(port >= CNUDFWorkerReservedPortBase && port < CNUDFWorkerReservedPortBase+CNUDFWorkerReservedPortSlots) ||
		port == CNUDFWorkerReservedMetricsPort
}

