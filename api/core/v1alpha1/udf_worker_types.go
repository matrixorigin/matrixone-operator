// These limits are part of the bounded status contract. They apply before a
// status observation is copied into a Kubernetes Condition or stored in a Pod
// annotation, so a malformed or stale producer cannot turn status refreshes
// into an unbounded control-plane payload.
const (
	UDFWorkerStatusMaxStringBytes     = 1024
	UDFWorkerStatusMaxListItems       = 64
	UDFWorkerStatusMaxListItemBytes   = 256
	UDFWorkerStatusMaxAnnotationBytes = 64 << 10
)

// UDFWorkerPolicy is the single typed policy used at the CNSet boundary. A
// nil policy means disabled. A non-nil policy with Enabled=false is an
// explicit, presence-aware disable and must not create worker resources.
//
// The policy intentionally contains no source code, artifact URI, command,
// args, or arbitrary Pod overlay. Function identity and executable artifact
// ownership belong to MatrixOne's Catalog/runtime contracts.
type UDFWorkerPolicy struct {
	// Enabled is the explicit feature switch. It is not inferred from any
	// image, port, or client setting.
	Enabled bool `json:"enabled,omitempty"`

	// +kubebuilder:validation:Enum=disabled;paired;pool
	Topology UDFWorkerTopology `json:"topology,omitempty"`

	// +kubebuilder:validation:Enum=python-image;mo-service
	Launcher UDFWorkerLauncher `json:"launcher,omitempty"`

	Worker UDFWorkerSpec   `json:"worker,omitempty"`
	Client UDFClientConfig `json:"client,omitempty"`

	// Pool is meaningful only for the future independent worker pool
	// topology. It is retained as typed configuration so current admission can
	// reject it without interpreting replicas as a same-Pod worker count.
	// +optional
	Pool *UDFWorkerPoolSpec `json:"pool,omitempty"`
}

// UDFWorkerSpec contains only structured workload properties controlled by
// the Operator. For the current same-Pod topology, scheduling and service
// account fields must remain empty because the worker shares the CN Pod.
type UDFWorkerSpec struct {
	// Image must be an immutable digest for an enabled policy.
	Image string `json:"image,omitempty"`

	// +kubebuilder:validation:Enum=Always;Never;IfNotPresent
	ImagePullPolicy corev1.PullPolicy `json:"imagePullPolicy,omitempty"`

	// Port is the worker's Pod-local Flight port. The Operator owns the bind
	// address and always renders 127.0.0.1 for same-Pod workers. It cannot use
	// a port occupied by the CN SQL, internal service, or metrics endpoints.
	// +kubebuilder:validation:Minimum=1
	// +kubebuilder:validation:Maximum=65535
	Port int32 `json:"port,omitempty"`

	Resources corev1.ResourceRequirements `json:"resources,omitempty"`

	// These fields are reserved for an external Worker workload. They are
	// rejected for the current same-Pod implementation.
	NodeSelector       map[string]string   `json:"nodeSelector,omitempty"`
	Tolerations        []corev1.Toleration `json:"tolerations,omitempty"`
	ServiceAccountName string              `json:"serviceAccountName,omitempty"`

	UpdateStrategy UDFWorkerUpdateStrategy `json:"updateStrategy,omitempty"`
	MOService      *UDFWorkerMOServiceSpec `json:"moService,omitempty"`
}

type UDFWorkerUpdateStrategy struct {
	// DrainTimeout is used by the future external route owner. Same-Pod
	// workers are drained with the CNSet Pod lifecycle.
	// +optional
	DrainTimeout *metav1.Duration `json:"drainTimeout,omitempty"`
}

type UDFWorkerMOServiceSpec struct {
	// Path and Python are consumed by the future external mo-service launcher.
	// UUID and address are generated from workload identity and are never
	// accepted from the user.
	Path   string `json:"path,omitempty"`
	Python string `json:"python,omitempty"`
}

