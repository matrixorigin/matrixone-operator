// IsValidUDFRuntimeErrorClass recognizes only errors produced by MO's Python
// runtime status protocol. Controller observation failures are a separate set.
func IsValidUDFRuntimeErrorClass(value string) bool {
	switch value {
	case "", "DISABLED", "NOT_ALLOWED", "UNAVAILABLE", "CONTRACT_MISMATCH", "TIMEOUT", "CLOSED", "INVALID", "INTERNAL":
		return true
	default:
		return false
	}
}

func IsValidUDFWorkerStatusErrorClass(value string) bool {
	if IsValidUDFRuntimeErrorClass(value) {
		return true
	}
	switch value {
	case "",
		UDFWorkerStatusErrorQueryUnavailable,
		UDFWorkerStatusErrorIdentityMismatch,
		UDFWorkerStatusErrorPolicyMismatch,
		UDFWorkerStatusErrorInvalid,
		UDFWorkerStatusErrorStale:
		return true
	default:
		return false
	}
}

// ValidateUDFWorkerPodStatus validates the bounded, controller-facing part of
// a per-Pod Python capability observation. Freshness and Pod/generation fences
// are intentionally checked by the consumer because they require live state.
func ValidateUDFWorkerPodStatus(status *UDFWorkerPodStatus) error {
	if status == nil {
		return fmt.Errorf("nil Python UDF worker status")
	}
	for name, value := range map[string]string{
		"podUID":                  status.PodUID,
		"cnUUID":                  status.CNUUID,
		"generation":              status.Generation,
		"errorClass":              status.ErrorClass,
		"reason":                  status.Reason,
		"abiContract":             status.ABIContract,
		"adapterVersion":          status.AdapterVersion,
		"sdkVersion":              status.SDKVersion,
		"typeDescriptorContract":  status.TypeDescriptorContract,
		"timezoneDatabaseVersion": status.TimezoneDatabaseVersion,
	} {
		if len(value) > UDFWorkerStatusMaxStringBytes {
			return fmt.Errorf("Python UDF worker status %s exceeds %d bytes", name, UDFWorkerStatusMaxStringBytes)
		}
	}
	if !IsValidUDFWorkerStatusErrorClass(status.ErrorClass) {
		return fmt.Errorf("unknown Python UDF worker status error class %q", status.ErrorClass)
	}
	for name, values := range map[string][]string{
		"modes":        status.Modes,
		"nullPolicies": status.NullPolicies,
	} {
		if len(values) > UDFWorkerStatusMaxListItems {
			return fmt.Errorf("Python UDF worker status %s has too many entries", name)
		}
		for _, value := range values {
			if len(value) > UDFWorkerStatusMaxListItemBytes {
				return fmt.Errorf("Python UDF worker status %s entry exceeds %d bytes", name, UDFWorkerStatusMaxListItemBytes)
			}
		}
	}
	return nil
}

// UDFWorkerPolicyGeneration returns the stable identity of the accepted
// worker policy. The same function is used by rendering and status fencing so
// an annotation from an older image, resource, client bound, or port cannot
// make a new policy look ready.
func UDFWorkerPolicyGeneration(policy *UDFWorkerPolicy) string {
	if policy == nil || !policy.Enabled {
		return ""
	}
	canonical := policy.DeepCopy()
	if canonical.Worker.Port == 0 {
		canonical.Worker.Port = ContainerUDFWorkerDefaultPort
	}
	if canonical.Worker.ImagePullPolicy == "" {
		canonical.Worker.ImagePullPolicy = corev1.PullIfNotPresent
	}
	if canonical.Client.RequestTimeout != nil && canonical.Client.RequestTimeout.Duration == 0 {
		canonical.Client.RequestTimeout = nil
	}
	if canonical.Client.TerminalRecordTTL != nil && canonical.Client.TerminalRecordTTL.Duration == 0 {
		canonical.Client.TerminalRecordTTL = nil
	}
	b, err := json.Marshal(canonical)
	if err != nil {
		return ""
	}
	digest := sha256.Sum256(append([]byte("matrixone-python-udf-worker-policy:"), b...))
	return hex.EncodeToString(digest[:])
}

// IsImmutableImageDigest accepts the image identity form used by the
// Kubernetes workload. A tag plus an arbitrary "@sha256:" suffix is not an
// immutable identity; the digest must contain exactly 32 bytes of hex data.
func IsImmutableImageDigest(image string) bool {
	const prefix = "@sha256:"
	if image == "" || strings.IndexFunc(image, unicode.IsSpace) >= 0 {
		return false
	}
	index := strings.LastIndex(image, prefix)
	if index <= 0 || strings.Count(image, prefix) != 1 || len(image)-index-len(prefix) != hex.EncodedLen(sha256DigestBytes) {
		return false
	}
	_, err := hex.DecodeString(image[index+len(prefix):])
	return err == nil
}

const sha256DigestBytes = 32

func (p *UDFWorkerPolicy) IsEnabled() bool {
	return p != nil && p.Enabled
}

func (p *UDFWorkerPolicy) EffectiveTopology() UDFWorkerTopology {
	if !p.IsEnabled() {
		return UDFWorkerTopologyDisabled
	}
	return p.Topology
}

func (p *UDFWorkerPolicy) EffectivePort() int32 {
	if p == nil || p.Worker.Port == 0 {
		return ContainerUDFWorkerDefaultPort
	}
	return p.Worker.Port
}

func (p *UDFWorkerPolicy) EffectiveImagePullPolicy() corev1.PullPolicy {
	if p == nil || p.Worker.ImagePullPolicy == "" {
		return corev1.PullIfNotPresent
	}
	return p.Worker.ImagePullPolicy
}

// Validate performs policy checks independent of an admission field path. The
// webhook adds precise field locations and the controller calls this method
// defensively when a webhook was bypassed during restore or by an older
// controller.
func (p *UDFWorkerPolicy) Validate() error {
	if p == nil {
		return nil
	}
	if p.Topology != "" && p.Topology != UDFWorkerTopologyDisabled &&
		p.Topology != UDFWorkerTopologyPaired && p.Topology != UDFWorkerTopologyPool {
		return fmt.Errorf("UnsupportedUDFWorkerTopology: %q", p.Topology)
	}
	if err := validateUDFClientConfig(&p.Client); err != nil {
		return err
	}
	if !p.Enabled {
		return nil
	}
	if p.Topology == "" {
		return fmt.Errorf("UDFWorkerTopologyRequired")
	}
	if p.Topology != UDFWorkerTopologyPaired && p.Topology != UDFWorkerTopologyPool {
		return fmt.Errorf("UnsupportedUDFWorkerTopology: %q", p.Topology)
	}
	if p.Topology == UDFWorkerTopologyPool {
		return fmt.Errorf("UnsupportedUDFWorkerTopology: pool")
	}
	if p.Pool != nil {
		return fmt.Errorf("UDFWorkerPoolConfigNotAllowedForPaired")
	}
	if p.Launcher == "" {
		return fmt.Errorf("UDFWorkerLauncherRequired")
	}
	if p.Launcher == UDFWorkerLauncherMOService {
		return fmt.Errorf("UnsupportedSamePodMoServiceLauncher")
	}
	if p.Launcher != UDFWorkerLauncherPythonImage {
		return fmt.Errorf("UnsupportedUDFWorkerLauncher: %q", p.Launcher)
	}
	if !IsImmutableImageDigest(p.Worker.Image) {
		return fmt.Errorf("UDFWorkerImageMustUseDigest")
	}
	if p.Worker.Port != 0 && (p.Worker.Port < 1 || p.Worker.Port > 65535) {
		return fmt.Errorf("UDFWorkerPortOutOfRange")
	}
	if IsCNPodPortReservedForUDFWorker(p.EffectivePort()) {
		return fmt.Errorf("UDFWorkerPortConflictsWithCN")
	}
	if p.Worker.ImagePullPolicy != "" &&
		p.Worker.ImagePullPolicy != corev1.PullAlways &&
		p.Worker.ImagePullPolicy != corev1.PullNever &&
		p.Worker.ImagePullPolicy != corev1.PullIfNotPresent {
		return fmt.Errorf("UnsupportedUDFWorkerImagePullPolicy: %q", p.Worker.ImagePullPolicy)
	}
	if !IsFinitePositiveQuantity(p.Worker.Resources.Limits.Cpu()) || !IsFinitePositiveQuantity(p.Worker.Resources.Limits.Memory()) {
		return fmt.Errorf("UDFWorkerResourceLimitsRequired")
	}
	if !IsFiniteNonNegativeQuantity(p.Worker.Resources.Requests.Cpu()) ||
		!IsFiniteNonNegativeQuantity(p.Worker.Resources.Requests.Memory()) {
		return fmt.Errorf("UDFWorkerRequestsOutOfRange")
	}
	if p.Worker.Resources.Requests.Cpu().Cmp(*p.Worker.Resources.Limits.Cpu()) > 0 ||
		p.Worker.Resources.Requests.Memory().Cmp(*p.Worker.Resources.Limits.Memory()) > 0 {
		return fmt.Errorf("UDFWorkerLimitBelowRequest")
	}
	if len(p.Worker.NodeSelector) != 0 || len(p.Worker.Tolerations) != 0 || p.Worker.ServiceAccountName != "" {
		return fmt.Errorf("UnsupportedSamePodWorkerScheduling")
	}
	if p.Worker.UpdateStrategy.DrainTimeout != nil {
		return fmt.Errorf("UnsupportedSamePodWorkerUpdateStrategy")
	}
	if p.Worker.MOService != nil {
		return fmt.Errorf("UnsupportedSamePodMoServiceConfig")
	}
	if !p.Client.AllowUnisolated {
		return fmt.Errorf("UDFWorkerRequiresAllowUnisolated")
	}
	return nil
}

// IsFinitePositiveQuantity is the common resource-limit predicate used by
// both API/controller validation and admission. Sign alone is insufficient:
// resource.Quantity can represent a positive value whose float conversion is
// infinite, which is not a meaningful cgroup limit.
func IsFinitePositiveQuantity(q *resource.Quantity) bool {
	if q == nil || q.Sign() <= 0 {
		return false
	}
	v := q.AsApproximateFloat64()
	return v > 0 && !math.IsInf(v, 0) && !math.IsNaN(v)
}

// IsFiniteNonNegativeQuantity accepts an omitted or zero request, but rejects
// negative, overflowing, NaN-like, and underflowed quantities before they are
// compared with a limit. The Kubernetes API normally validates these fields;
// this helper also protects restore and controller paths that bypass admission.
func IsFiniteNonNegativeQuantity(q *resource.Quantity) bool {
	if q == nil || q.Sign() == 0 {
		return true
	}
	return IsFinitePositiveQuantity(q)
}

func validateUDFClientConfig(c *UDFClientConfig) error {
	if c.MaxBatchBytes < 0 || c.MaxBatchBytes > 1<<30 {
		return fmt.Errorf("UDFClientMaxBatchBytesOutOfRange")
	}
	if c.MaxBatchRows < 0 || c.MaxBatchRows > 1<<30 {
		return fmt.Errorf("UDFClientMaxBatchRowsOutOfRange")
	}
	if c.MaxInvocationRows < 0 || c.MaxInvocationRows > 1<<32 {
		return fmt.Errorf("UDFClientMaxInvocationRowsOutOfRange")
	}
	if c.MaxInvocationResultBytes < 0 || c.MaxInvocationResultBytes > 1<<40 {
		return fmt.Errorf("UDFClientMaxInvocationResultBytesOutOfRange")
	}
	if c.MaxActiveInvocations < 0 || c.MaxActiveInvocations > 1<<20 {
		return fmt.Errorf("UDFClientMaxActiveInvocationsOutOfRange")
	}
	if c.RequestTimeout != nil && (c.RequestTimeout.Duration < 0 || c.RequestTimeout.Duration > time.Hour) {
		return fmt.Errorf("UDFClientRequestTimeoutOutOfRange")
	}
	if c.MaxTerminalEntries < 0 || c.MaxTerminalEntries > 1<<30 {
		return fmt.Errorf("UDFClientMaxTerminalEntriesOutOfRange")
	}
	if c.MaxTerminalBytes < 0 || c.MaxTerminalBytes > 1<<40 {
		return fmt.Errorf("UDFClientMaxTerminalBytesOutOfRange")
	}
	if c.TerminalRecordTTL != nil && c.TerminalRecordTTL.Duration < 0 {
		return fmt.Errorf("UDFClientTerminalRecordTTLOutOfRange")
	}
	return nil
}
